import subprocess
import sys
import threading
import tkinter as tk
from tkinter import scrolledtext, ttk


class TaskRunnerApp:

    def __init__(self, root: tk.Tk):
        self.root = root
        self.root.title("Task Runner")
        self.root.geometry("750x450")

        self.process: subprocess.Popen | None = None
        self.last_command: list[str] | None = None

        # --- Top Button Bar ---
        btn_frame = ttk.Frame(root, padding=10)
        btn_frame.pack(fill=tk.X)

        self.btn_x = ttk.Button(
            btn_frame,
            text="Run X",
            command=lambda: self.start_task(
                [sys.executable, "-c", "import time; [print(f'X step {i}', flush=True) or time.sleep(0.5) for i in range(10)]"]
            ),
        )
        self.btn_x.pack(side=tk.LEFT, padx=(0, 5))

        self.btn_y = ttk.Button(
            btn_frame,
            text="Run Y",
            command=lambda: self.start_task(["ping", "127.0.0.1", "-n", "5"]),
        )
        self.btn_y.pack(side=tk.LEFT, padx=5)

        self.btn_halt = ttk.Button(
            btn_frame, text="Halt", command=self.halt_task, state=tk.DISABLED
        )
        self.btn_halt.pack(side=tk.LEFT, padx=5)

        self.btn_relaunch = ttk.Button(
            btn_frame,
            text="Relaunch",
            command=self.relaunch_task,
            state=tk.DISABLED,
        )
        self.btn_relaunch.pack(side=tk.LEFT, padx=5)

        ttk.Button(btn_frame, text="Clear Log", command=self.clear_log).pack(
            side=tk.RIGHT
        )

        # --- Scrolling Console Output ---
        self.log_box = scrolledtext.ScrolledText(
            root,
            wrap=tk.WORD,
            state=tk.DISABLED,
            bg="#1e1e1e",
            fg="#d4d4d4",
            font=("Consolas", 10),
        )
        self.log_box.pack(fill=tk.BOTH, expand=True, padx=10, pady=(0, 10))

    def append_log(self, text: str):
        # Schedule UI update safely on the main thread
        def _write():
            self.log_box.configure(state=tk.NORMAL)
            self.log_box.insert(tk.END, text)
            self.log_box.see(tk.END)
            self.log_box.configure(state=tk.DISABLED)

        self.root.after(0, _write)

    def clear_log(self):
        self.log_box.configure(state=tk.NORMAL)
        self.log_box.delete("1.0", tk.END)
        self.log_box.configure(state=tk.DISABLED)

    def set_running_state(self, is_running: bool):
        def _update():
            self.btn_x.configure(
                state=tk.DISABLED if is_running else tk.NORMAL
            )
            self.btn_y.configure(
                state=tk.DISABLED if is_running else tk.NORMAL
            )
            self.btn_halt.configure(
                state=tk.NORMAL if is_running else tk.DISABLED
            )
            self.btn_relaunch.configure(
                state=tk.NORMAL if self.last_command else tk.DISABLED
            )

        self.root.after(0, _update)

    def start_task(self, cmd: list[str]):
        if self.process and self.process.poll() is None:
            return

        self.last_command = cmd
        self.append_log(f"\n>>> Starting: {' '.join(cmd)}\n")
        self.set_running_state(True)

        threading.Thread(
            target=self._run_subprocess, args=(cmd,), daemon=True
        ).start()

    def _run_subprocess(self, cmd: list[str]):
        try:
            # creationflags=CREATE_NO_WINDOW prevents a secondary black cmd box from popping up
            self.process = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                bufsize=1,
                creationflags=subprocess.CREATE_NO_WINDOW,
            )
            assert self.process.stdout is not None
            for line in self.process.stdout:
                self.append_log(line)

            code = self.process.wait()
            self.append_log(f">>> Finished (exit code {code})\n")
        except Exception as exc:
            self.append_log(f">>> Error: {exc}\n")
        finally:
            self.set_running_state(False)

    def halt_task(self):
        if self.process and self.process.poll() is None:
            self.append_log(">>> Halting process...\n")
            self.process.terminate()

    def relaunch_task(self):
        if not self.last_command:
            return
        if self.process and self.process.poll() is None:
            self.halt_task()
            # Give the OS a moment to clean up before restarting
            self.root.after(300, lambda: self.start_task(self.last_command))
        else:
            self.start_task(self.last_command)


if __name__ == "__main__":
    root = tk.Tk()
    app = TaskRunnerApp(root)
    root.mainloop()
